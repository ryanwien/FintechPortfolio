"""Markdown run report (``results/REPORT.md``) rendered from the metrics dict.

Pure function of ``metrics.json`` content: no computation beyond formatting, so the report can
never disagree with the machine-readable results.
"""

from __future__ import annotations

import json
from typing import Any

from fraud.catalog import FRAUD_TYPES
from fraud.evaluation import MODELS


def usd(cents: int) -> str:
    """Whole-dollar string for an integer-cent amount, e.g. ``-$1,234``."""
    sign = "-" if cents < 0 else ""
    return f"{sign}${abs(cents) / 100:,.0f}"


def _psi_rows(m: dict[str, Any], a: str, b: str) -> list[str]:
    """Drift table rows: PSI on comparison ``a`` and ``b``, ordered by ``b``."""
    first = {r["feature"]: r["psi"] for r in m["drift"][a]}
    out = []
    for r in m["drift"][b]:
        out.append(
            f"| {r['feature']} | {first[r['feature']]:.3f} | {r['psi']:.3f} | {r['status']} |"
        )
    return out


def render_report(m: dict[str, Any]) -> str:
    """Render the full markdown report from a metrics dict produced by ``fraud.run``."""
    d = m["data"]
    sp = d["split"]
    mr = m["models"]
    dec = m["decisioning"]["per_model"]
    sv = m["decisioning"]["savings"]
    sk = m["feature_engine"]["train_serve_skew"]
    lat = m["latency"]
    dr = m["drift"]
    c = m["config"]["costs"]
    lines = [
        "# Real-time card fraud scoring: run report",
        "",
        f"Generated by `python -m fraud.run` (seed {m['run']['seed']}, runtime "
        f"{m['run']['runtime_seconds']:.0f}s). Every number below comes from that run.",
        "",
        "## Data",
        "",
        f"- {d['n_txns']:,} synthetic transactions from {d['n_customers']:,} customers; "
        f"{d['fraud_txns']:,} fraud ({d['fraud_rate']:.2%}).",
        "- Fraud by type: " + ", ".join(f"{k} {v:,}" for k, v in d["fraud_by_type"].items()) + ".",
        f"- Time split ({sp['period_days']}-day months): warm-up {sp['warmup_periods']} "
        f"(feature history only), train {sp['train_periods']} ({sp['n_train']:,} txns), "
        f"validation {sp['valid_periods']} ({sp['n_valid']:,}), test {sp['test_periods']} "
        f"({sp['n_test']:,}), shifted month {sp['shifted_period']} ({sp['n_shifted']:,}).",
        f"- Label delay: median {d['label_delay_days']['median']:.1f} days, p90 "
        f"{d['label_delay_days']['p90']:.1f} days. At the training cut-off "
        f"{d['train_fraud_unlabelled_share']:.1%} of training-window fraud had not been "
        "reported yet, so the model trained on it as 'good'.",
        "",
        "## Model comparison (test months, matured labels)",
        "",
        "| Model | PR-AUC | ROC-AUC | Recall @ 0.5% alerts | Precision @ 0.5% | "
        "Recall @ 2% alerts | Brier |",
        "|---|---|---|---|---|---|---|",
    ]
    for name in MODELS:
        t = mr[name]["test"]
        r = t["recall_at_0.5pct_alerts"]
        brier = f"{t['brier']:.5f}" if "brier" in t else "n/a"
        lines.append(
            f"| {name} | {t['pr_auc']:.3f} | {t['roc_auc']:.3f} | {r['recall']:.1%} | "
            f"{r['precision']:.1%} | {t['recall_at_2pct_alerts']['recall']:.1%} | {brier} |"
        )
    lines += [
        "",
        f"Fraud is {mr['hgb']['test']['n_fraud'] / mr['hgb']['test']['n']:.2%} of test "
        f"traffic, so alerting on 0.5% can catch at most "
        f"{m['recall_ceiling_0.5pct']['test']:.1%} of it. Base-rate Brier (predict the "
        f"fraud rate for everyone): {mr['hgb']['test']['brier_base_rate']:.5f}.",
        "",
        "Recall at the 0.5% alert rate by fraud type:",
        "",
        "| Model | Split | " + " | ".join(FRAUD_TYPES) + " |",
        "|---|---|" + "---|" * len(FRAUD_TYPES),
    ]
    for name in MODELS:
        for split in ("test", "shifted"):
            row = m["recall_by_fraud_type_0.5pct"][name][split]
            lines.append(
                f"| {name} | {split} | "
                + " | ".join(f"{row.get(t, float('nan')):.1%}" for t in FRAUD_TYPES)
                + " |"
            )
    lines += [
        "",
        "friendly_fraud (a genuine purchase later disputed) is behaviourally identical to "
        "normal spend; 0% recall is the expected, honest result.",
        "",
        "### Calibration (HGB, test)",
        "",
        "| Score bin | n | mean predicted | observed fraud rate |",
        "|---|---|---|---|",
    ]
    for b in mr["hgb"]["test"]["reliability"]:
        lines.append(
            f"| [{b['bin'][0]}, {b['bin'][1]}) | {b['n']:,} | {b['mean_predicted']:.4f} | "
            f"{b['observed_rate']:.4f} |"
        )
    lines += [
        "",
        "Predicted probabilities sit below observed rates in the middle bins: the model was "
        "trained on labels as known at the cut-off (late chargebacks counted as good) and is "
        "evaluated on matured labels.",
        "",
        "## Cost-sensitive decisioning",
        "",
        f"Costs: missed fraud = full amount; review = ${c['review_cost_cents'] / 100:.2f} "
        f"analyst time, stops {c['review_catch_bps'] / 100:.0f}% of the fraud it sees, "
        f"${c['review_friction_cents'] / 100:.2f} friction for a good customer; false decline "
        f"= {c['decline_margin_bps'] / 100:.1f}% lost margin + "
        f"${c['decline_friction_cents'] / 100:.2f} customer friction. Review capacity "
        f"<= {c['max_review_rate']:.0%} of traffic. Bands are chosen on the validation month "
        "and applied unchanged to the test months.",
        "",
        "| Policy | Review if score in | Decline if score >= | Reviews | Declines | "
        "False declines | Fraud $ stopped | Expected loss (test) |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for name in MODELS:
        b = dec[name]["bands"]
        t = dec[name]["test"]
        stopped = t["fraud_cents_declined"] + t["fraud_cents_reviewed"]
        lines.append(
            f"| {name} | [{b['review_at']:.4g}, {b['decline_at']:.4g}) | {b['decline_at']:.4g} "
            f"| {t['review']:,} ({t['review_rate']:.2%}) | {t['decline']:,} | "
            f"{t['false_declines']:,} | {stopped / max(1, t['fraud_cents']):.1%} | "
            f"{usd(t['expected_loss_cents'])} |"
        )
    lines += [
        f"| approve all | - | - | 0 | 0 | 0 | 0% | {usd(sv['approve_all_loss_cents'])} |",
        "",
        f"**HGB cuts expected loss by {usd(sv['hgb_vs_rules_cents'])} vs the rules baseline "
        f"over {sv['test_months']} test months ({sv['hgb_vs_rules_pct']:.1%} lower, "
        f"{usd(sv['hgb_vs_rules_cents_per_month'])}/month)**, and by "
        f"{usd(sv['hgb_vs_logreg_cents'])} vs logistic regression.",
        "",
        "HGB loss breakdown (test): "
        + ", ".join(f"{k} {usd(v)}" for k, v in dec["hgb"]["test"]["loss_breakdown_cents"].items())
        + ".",
        "",
        f"Same frozen bands on the shifted month: HGB expected loss "
        f"{usd(dec['hgb']['shifted']['expected_loss_cents'])}, rules "
        f"{usd(dec['rules']['shifted']['expected_loss_cents'])}; fraud dollars approved "
        f"{usd(dec['hgb']['shifted']['fraud_cents_approved'])} of "
        f"{usd(dec['hgb']['shifted']['fraud_cents'])}.",
        "",
        "## Drift monitoring (PSI vs training months)",
        "",
        f"Thresholds: warn >= {dr['thresholds']['warn']}, alert >= {dr['thresholds']['alert']}."
        f" Model score PSI: test {dr['score_psi_train_vs_test']:.3f}, shifted month "
        f"{dr['score_psi_train_vs_shifted']:.3f} ({dr['score_status_shifted']}).",
        "",
        "All traffic (available in real time):",
        "",
        "| Feature | PSI test | PSI shifted | Status (shifted) |",
        "|---|---|---|---|",
        *_psi_rows(m, "train_vs_test", "train_vs_shifted"),
        "",
        "Fraud-only population (available once chargebacks arrive, weeks later):",
        "",
        "| Feature | PSI test | PSI shifted | Status (shifted) |",
        "|---|---|---|---|",
        *_psi_rows(m, "fraud_only_train_vs_test", "fraud_only_train_vs_shifted"),
        "",
        "Population PSI picks up the seasonal shift in legitimate spend (amount features) "
        "but cannot see the account-takeover tactic change: fraud is ~1% of traffic. The "
        "fraud-only PSI flags it once labels mature, and the model's ATO recall shows the "
        "damage:",
        "",
        f"- HGB PR-AUC {mr['hgb']['test']['pr_auc']:.3f} (test) -> "
        f"{mr['hgb']['shifted']['pr_auc']:.3f} (shifted); ATO recall @ 0.5% alerts "
        f"{m['recall_by_fraud_type_0.5pct']['hgb']['test']['ato']:.1%} -> "
        f"{m['recall_by_fraud_type_0.5pct']['hgb']['shifted']['ato']:.1%}.",
        "",
        "## Serving",
        "",
        f"- Model version `{m['model_version']}`.",
        f"- Train/serve skew: all {sk['rows_compared_in_process']:,} transactions replayed "
        f"through the serving `Scorer` give max |online - batch| feature difference "
        f"{sk['max_abs_feature_diff_in_process']:g}. Online scores (flat-array tree walk) vs "
        f"batch scores (sklearn) differ by at most {sk['max_abs_score_diff_in_process']:.1e} "
        f"over {sk['rows_scored_in_process']:,} requests. Through HTTP (JSON round trip, "
        f"{sk['rows_compared_http']:,} requests): {sk['max_abs_feature_diff_http']:g}.",
        f"- Feature engine throughput (batch replay, one core): "
        f"{m['feature_engine']['throughput_txn_per_sec']:,.0f} txns/s.",
        "",
        "| Path | n | p50 ms | p95 ms | p99 ms |",
        "|---|---|---|---|---|",
    ]
    for label, key in (
        (
            "In-process `Scorer.score`, reason codes on review/decline (production setting)",
            "in_process_production",
        ),
        ("In-process `Scorer.score`, reason codes on every request", "in_process_reasons_always"),
        ("FastAPI `POST /score` via in-process TestClient", "http_testclient"),
    ):
        p = lat[key]
        lines.append(
            f"| {label} | {p['n']:,} | {p['p50_ms']:.3f} | {p['p95_ms']:.3f} | {p['p99_ms']:.3f} |"
        )
    lines += [
        "",
        "Wall-clock, single thread, on the machine that produced this report. The TestClient "
        "row includes ASGI, JSON and pydantic validation overhead but no network.",
        "",
        "Highest-scoring `/score` response from the HTTP replay:",
        "",
        "```json",
        json.dumps(m["example_response"], indent=2),
        "```",
        "",
    ]
    return "\n".join(lines)
