"""Rendering of run outputs: ``REPORT.md``, ``sample_case.md`` and ``site.json``.

Every function here is a pure function of the metrics dict (or of the world, a case and
the audit log); nothing is hand-written into ``results/``. The sample case file also
demonstrates tamper detection on a copy of the audit log, never on the log itself.
"""

from __future__ import annotations

import json
from dataclasses import replace
from typing import Any, Final

from .audit import AuditLog, verify_chain
from .cases import L1_ANALYSTS, Case
from .model import MONITOR_START_DAY, World, fmt_cents, fmt_date, fmt_ts
from .narrative import draft_narrative
from .synth import TYPOLOGIES

PERCENT: Final = 100
HASH_PREVIEW_CHARS: Final = 12
HEAD_HASH_PREVIEW_CHARS: Final = 16
MULTI_FAMILY_MIN: Final = 2


def pct(x: float) -> str:
    """Fraction as a one-decimal percentage string."""
    return f"{PERCENT * x:.1f}%"


def pick_sample_case(cases: list[Case]) -> Case:
    """Most illustrative case: a filed network case, else a filed multi-family case,
    else the top case above the line, else the first case."""
    # Try the most illustrative predicates in order; the first group that is not empty wins.
    for pred in (
        lambda c: c.network_id and c.disposition == "SAR_FILED",
        lambda c: c.disposition == "SAR_FILED" and len(c.families) >= MULTI_FAMILY_MIN,
        lambda c: c.above_line,
    ):
        found = [c for c in cases if pred(c)]
        if found:
            # Within that group, the highest score (then the id) wins, so the choice is
            # deterministic.
            return min(found, key=lambda c: (-c.score, c.case_id))
    return cases[0]


def render_sample_case(world: World, case: Case, audit: AuditLog) -> str:
    """Markdown case file: summary, score breakdown, alerts, narrative, audit trail."""
    # Only this case's entries are shown; the hash chain itself is global across every case.
    entries = audit.for_case(case.case_id)
    lines = [
        f"# Case file {case.case_id}",
        "",
        "Generated by `python -m aml.run` from the synthetic world; nothing hand-written.",
        "",
        "| Field | Value |",
        "|---|---|",
        f"| Case key | {case.key} |",
        f"| Subjects | {', '.join(case.subjects)} |",
        f"| Risk score | {case.score} ({case.priority}) |",
        f"| Typology families | {', '.join(case.families)} |",
        f"| Opened | {fmt_ts(case.opened_ts)} |",
        f"| Assigned analyst | {case.analyst} |",
        f"| Disposition | {case.disposition} |",
        f"| Closed | {fmt_ts(case.closed_ts) if case.closed_ts else ''} |",
        "",
        "## Score breakdown",
        "",
        # Show the score's parts so a reviewer can see how the total was built up.
        f"- Rule contributions (weight x signal, pts): "
        f"{json.dumps(case.breakdown['rule_contributions'])}",
        f"- Corroboration bonus: {case.breakdown['corroboration_bonus']} pts",
        f"- KYC multiplier (max over subjects): {case.breakdown['kyc_multiplier']}",
        "",
        "## Subjects",
        "",
        "| Customer | Name | Type | Segment | KYC | Expected monthly |",
        "|---|---|---|---|---|---:|",
    ]
    for s in case.subjects:
        c = world.customers[s]
        lines.append(
            f"| {s} | {c.name} | {c.kind} | {c.segment} | {c.kyc_risk} | "
            f"{fmt_cents(c.expected_monthly_cents)} |"
        )
    lines += [
        "",
        "## Alerts",
        "",
        "| Alert | Rule | Customer | Window | Score | Txns |",
        "|---|---|---|---|---:|---:|",
    ]
    for a in case.alerts:
        lines.append(
            f"| {a.alert_id} | {a.rule_id} | {a.customer_id} | "
            f"{fmt_date(a.ts_start)} - {fmt_date(a.ts_end)} | {a.score:.2f} | "
            f"{len(a.txn_ids)} |"
        )
    lines += [
        "",
        "## SAR-candidate narrative",
        "",
        # Use the stored narrative when the case was escalated; otherwise draft one now so the file
        # is never empty.
        case.narrative or draft_narrative(world, case),
        "",
        "## Audit trail",
        "",
        "One global hash chain covers every case; gaps in `Seq` below are entries "
        "belonging to other cases.",
        "",
        "| Seq | Time | Actor | Action | Details | Prev hash | Hash |",
        "|---:|---|---|---|---|---|---|",
    ]
    for e in entries:
        det = "; ".join(f"{k}={v}" for k, v in e.details)
        lines.append(
            f"| {e.seq} | {fmt_ts(e.ts)} | {e.actor} | {e.action} | {det} | "
            f"`{e.prev_hash[:HASH_PREVIEW_CHARS]}` | `{e.entry_hash[:HASH_PREVIEW_CHARS]}` |"
        )
    # Verify the real log first; the tamper demonstration below runs on a copy and never touches it.
    full = audit.verify()
    # tamper demonstration on a copy: rewrite one of this case's entries
    # Copy the entries so the edit lives only in memory.
    tampered = list(audit.entries)
    # Tamper with the middle entry of this case; its seq is a global index into the copy.
    target = entries[len(entries) // 2]
    # Adding a field changes the content, so it no longer matches the stored hash.
    tampered[target.seq] = replace(target, details=(*target.details, ("edited", "true")))
    # Verification should fail at exactly that entry, which the line below reports.
    bad = verify_chain(tampered)
    lines += [
        "",
        f"Chain verification over the full log ({full.entries} entries): "
        f"**{'OK' if full.ok else 'FAILED'}**; head hash `{audit.head[:HEAD_HASH_PREVIEW_CHARS]}`.",
        "",
        f"Tamper check: adding a field to entry #{target.seq} on a copy of the log makes "
        f"verification fail at seq {bad.first_bad_seq} ({bad.reason}).",
        "",
    ]
    return "\n".join(lines)


def render_report(m: dict[str, Any]) -> str:
    """``REPORT.md`` from the metrics dict."""
    w, al, de, ca = m["world"], m["alerts"], m["detection"], m["cases"]
    an = m["analyst_simulation"]
    lines = [
        "# AML monitoring - results",
        "",
        f"Config `{m['config']}` | seed {m['seed']} | {w['customers']:,} customers, "
        f"{w['accounts']:,} accounts, {w['transactions']:,} transactions, "
        f"{w['monitoring_days']}-day monitoring window after a {MONITOR_START_DAY}-day lookback.",
        f"Ground truth: {w['suspicious_customers']} suspicious customers in "
        f"{w['typology_instances']} injected typology instances.",
        "",
        "## Headline",
        "",
        "| Metric | Value |",
        "|---|---:|",
        "| Typology instance detection (any alert) | "
        f"{pct(de['instance_detection_rate_alerts'])} |",
        f"| Typology instance detection (above the line, score >= {ca['line']}) | "
        f"{pct(de['instance_detection_rate_at_line'])} |",
        f"| Alerts | {al['total']} ({al['per_1k_customers']} per 1k customers) |",
        f"| Alert precision | {pct(al['precision'])} |",
        f"| False-positive rate (benign customers alerted) | {pct(al['false_positive_rate'])} |",
        f"| Cases above / below the line | {ca['above_line']} / {ca['below_line']} |",
        f"| Case precision above the line | {pct(ca['precision_above_line'])} |",
        f"| Cases above the line per 1k customers | {ca['per_1k_customers_above_line']} |",
        f"| SARs filed (simulated analysts) | {an['sars_filed']} of {an['cases_reviewed']} "
        f"reviewed ({pct(an['sar_conversion_rate'])}) |",
        f"| Audit chain | {m['audit']['entries']} entries, verified={m['audit']['verified']} |",
        "",
        "## Detection by typology",
        "",
        "| Typology | Instances | Detected (alerts) | Detected (at line) "
        "| Members covered (at line)"
        " | Variants (instances / alerted / at line) |",
        "|---|---:|---:|---:|---:|---|",
    ]
    for typ, d in de["per_typology"].items():
        # One row per typology; the variants are flattened into one cell so each typology stays on
        # one line.
        var = "; ".join(
            f"{k}: {v['instances']}/{v['alerted']}/{v['at_line']}"
            for k, v in d["by_variant"].items()
        )
        lines.append(
            f"| {typ} | {d['instances']} | {pct(d['detection_rate_alerts'])} | "
            f"{pct(d['detection_rate_at_line'])} | "
            f"{pct(d['member_coverage_at_line'])} | {var} |"
        )
    lines += [
        "",
        "## Alerts by rule",
        "",
        "| Rule | Alerts | True positive | Precision |",
        "|---|---:|---:|---:|",
    ]
    for r, d in al["per_rule"].items():
        lines.append(f"| {r} | {d['alerts']} | {d['true_positive']} | {pct(d['precision'])} |")
    lines += [
        "",
        "## Benign look-alikes (where false positives come from)",
        "",
        "| Segment | Customers | Alerted | In a case above the line |",
        "|---|---:|---:|---:|",
    ]
    for seg, d in m["benign_lookalikes"].items():
        lines.append(f"| {seg} | {d['customers']} | {d['alerted']} | {d['in_case_above_line']} |")
    lines += [
        "",
        "## Analyst simulation",
        "",
        f"Cases worked in priority-queue order by {len(L1_ANALYSTS)} L1 analysts, "
        "escalations to L2 and QA. "
        f"Decisions follow ground truth with noise. SARs on true cases: "
        f"{an['sars_on_true_cases']}; on benign cases: {an['sars_on_benign_cases']}; true "
        f"cases closed without SAR: {an['true_cases_closed_without_sar']}; decision accuracy "
        f"{pct(an['decision_accuracy'])}.",
        "",
        "## Above/below the line: case-score threshold sweep",
        "",
        "| Line | Cases | Cases per 1k | Typology detection | Case precision |",
        "|---:|---:|---:|---:|---:|",
    ]
    for p in m["line_sweep"]:
        lines.append(
            f"| {p['line']:.0f} | {p['cases']} | {p['cases_per_1k']} | "
            f"{pct(p['detection_rate'])} | {pct(p['case_precision'])} |"
        )
    # Sweep tables follow: one per rule, showing how precision and target detection move with the
    # threshold.
    lines += ["", "## Rule threshold sweeps (one rule at a time)", ""]
    for name, pts in m["rule_sweeps"].items():
        # Every point in one sweep shares a target typology, so the table header can take it from
        # the first point.
        target = pts[0]["target_typology"]
        lines += [
            f"**{name}** (target typology: {target})",
            "",
            "| Value | Alerts | True positive | Precision | Target detection |",
            "|---:|---:|---:|---:|---:|",
        ]
        for p in pts:
            lines.append(
                f"| {p['value']} | {p['alerts']} | {p['true_positive']} | "
                f"{pct(p['precision'])} | {pct(p['target_detection_rate'])} |"
            )
        lines.append("")
    return "\n".join(lines)


