"""Rendering of benchmark results: ``metrics.json``, ``REPORT.md`` and ``site.json``.

Pure formatting over the metrics dict built by :mod:`ledger.bench`; nothing
here measures or touches the ledger.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any, Final

from ledger.config import OVERDRAFT_HOLD_FRACTION

CONCURRENCY_HEADERS: Final = [
    "threads",
    "transfers",
    "transfers/s",
    "postings/s",
    "p50 ms",
    "p95 ms",
    "p99 ms",
    "invariants + conservation",
]
RECON_HEADERS: Final = ["break type", "injected", "detected", "correct", "precision", "recall"]


def md_table(headers: list[str], rows: list[list[Any]]) -> str:
    """A GitHub-flavoured Markdown table."""
    out = ["| " + " | ".join(headers) + " |", "|" + "---|" * len(headers)]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def _concurrency_rows(m: dict[str, Any]) -> list[list[Any]]:
    """Table rows for the transfers-by-concurrency section of the report."""
    return [
        [
            r["threads"],
            r["transfers"],
            r["transfers_per_s"],
            r["postings_per_s"],
            r["latency_ms"]["p50"],
            r["latency_ms"]["p95"],
            r["latency_ms"]["p99"],
            "yes" if r["invariants_ok"] and r["money_conserved"] else "NO",
        ]
        for r in m["transfers"]["by_concurrency"]
    ]


def _recon_rows(r: dict[str, Any]) -> list[list[Any]]:
    """Table rows, one per break type, for a reconciliation run."""
    return [
        [k, v["injected"], v["detected"], v["true_positive"], v["precision"], v["recall"]]
        for k, v in r["scoring"]["per_kind"].items()
    ]


def render_report(m: dict[str, Any]) -> str:
    """The Markdown benchmark report."""
    env = m["environment"]
    by_conc = m["transfers"]["by_concurrency"]
    seq, last = by_conc[0], by_conc[-1]
    nrm = m["transfers"]["synchronous_normal"]
    lc = m["lifecycle"]
    rc = m["reconciliation"]["standard"]
    rh = m["reconciliation"]["stress"]
    s = rc["summary"]

    header = (
        "# Ledger benchmark report\n\n"
        f"Generated by `python -m ledger.bench` on {env['generated_at']}.\n"
        f"Environment: Python {env['python']}, SQLite {env['sqlite']},\n"
        f"{env['platform']}. Database: file-backed SQLite, WAL, `synchronous=FULL`\n"
        "unless noted. Latency is per `create_payment` call through the service layer"
        " (no HTTP).\n"
    )
    transfers = (
        "## Transfers by concurrency\n\n"
        f"{md_table(CONCURRENCY_HEADERS, _concurrency_rows(m))}\n\n"
        "SQLite has a single writer, so threads queue on the write lock:"
        " throughput does not scale with\n"
        f"threads ({seq['transfers_per_s']} -> {last['transfers_per_s']} transfers/s\n"
        f"from 1 to {last['threads']} threads) and p99 grows with queue depth.\n"
        "Same single-thread load with `synchronous=NORMAL`\n"
        f"(fsync at checkpoint only): {nrm['transfers_per_s']} transfers/s,"
        f" p99 {nrm['latency_ms']['p99']} ms.\n"
    )
    lifecycle = (
        "## Payment lifecycle and idempotency\n\n"
        f"- authorize (hold) p50 {lc['authorize_ms_p50']} ms / p99 {lc['authorize_ms_p99']} ms;\n"
        f"  capture p50 {lc['capture_ms_p50']} ms / p99 {lc['capture_ms_p99']} ms\n"
        f"- idempotent replay p50 {lc['replay_ms_p50']} ms"
        f" vs first write p50 {lc['first_write_ms_p50']} ms;\n"
        f"  {lc['replays_served_from_store']}/{lc['replays_attempted']}"
        " retries served from the stored response\n"
        f"- overdraft guard: {lc['holds_accepted_before_overdraft']} holds of"
        f" 1/{OVERDRAFT_HOLD_FRACTION} of the balance accepted,\n"
        f"  {lc['holds_rejected_insufficient_funds']} rejected with `insufficient_funds`\n"
    )
    recon = (
        "## Reconciliation\n\n"
        f"Standard injection rates, period {rc['period']}: {s['ledger_items']}"
        " ledger movements on\n"
        f"the cash account vs {s['bank_lines']} bank lines; auto-match rate\n"
        f"{s['auto_match_rate']:.2%}; {s['breaks']} breaks; difference\n"
        f"{s['difference']} minor units, of which {s['explained_by_breaks']} explained by\n"
        f"classified breaks (unexplained: {s['unexplained_difference']}). Matching took\n"
        f"{rc['reconcile_ms']} ms.\n\n"
        f"{md_table(RECON_HEADERS, _recon_rows(rc))}\n\n"
        "Stress rates (4x breaks; 35% of bank memos stripped of the reference,"
        " which settle 0-3 days\n"
        "late, so some fall outside the 1-day matching tolerance with no reference"
        " to fall back on): precision\n"
        f"{rh['scoring']['precision']}, recall {rh['scoring']['recall']},"
        " unexplained difference\n"
        f"{rh['summary']['unexplained_difference']}.\n\n"
        f"{md_table(RECON_HEADERS, _recon_rows(rh))}\n"
    )
    return "\n".join([header, transfers, lifecycle, recon])


def site_summary(m: dict[str, Any]) -> dict[str, Any]:
    """The portfolio-site card for this project."""
    by_conc = m["transfers"]["by_concurrency"]
    seq = by_conc[0]
    best = max(by_conc, key=lambda r: r["transfers_per_s"])
    rc = m["reconciliation"]["standard"]
    scoring = rc["scoring"]
    return {
        "slug": "ledger",
        "title": "Double-entry ledger & payments API",
        "tagline": "An append-only, double-entry ledger with idempotent payments, "
        "authorization holds and automated bank reconciliation.",
        "lane": "Payments infrastructure",
        "stack": ["Python", "FastAPI", "SQLite", "Hypothesis", "pytest"],
        "metrics": [
            {
                "label": "p99 transfer latency",
                "value": f"{seq['latency_ms']['p99']}",
                "unit": "ms",
                "note": "single writer, fsync on every commit (synchronous=FULL)",
            },
            {
                "label": "transfer throughput",
                "value": f"{best['transfers_per_s']:.0f}",
                "unit": "transfers/s",
                "note": f"{best['postings_per_s']:.0f} postings/s at {best['threads']} thread(s)",
            },
            {
                "label": "recon break classification",
                "value": f"{scoring['precision']:.0%}",
                "unit": "precision",
                "note": f"{scoring['correctly_classified']}/{scoring['injected_breaks']} "
                f"injected breaks, recall {scoring['recall']:.0%}",
            },
            {
                "label": "unexplained recon difference",
                "value": str(rc["summary"]["unexplained_difference"]),
                "unit": "cents",
                "note": "every cent of bank vs ledger difference attributed to a break",
            },
        ],
        "highlights": [
            "Append-only journal enforced by SQLite triggers; corrections are reversing entries",
            "Idempotency keys stored in the same transaction as the effect: "
            "exactly-once under retries",
            "Authorization holds: available vs pending balance, overdraft rule checked atomically",
            "Hypothesis state machine: random operation sequences never unbalance the books",
            "Reconciliation classifies missing, duplicate, amount and timing breaks "
            "against a bank file",
        ],
        "limitations": [
            "SQLite has one writer: throughput is flat with concurrency; "
            "Postgres row locks would scale",
            "Bank statement is synthetic; its generator and the matcher were written together",
            "Single-currency transfers; FX is only possible as hand-built multi-leg entries",
        ],
        "series": {
            "name": "transfers/s by concurrent threads (synchronous=FULL)",
            "x": [r["threads"] for r in by_conc],
            "y": [r["transfers_per_s"] for r in by_conc],
        },
    }


def write_outputs(m: dict[str, Any], results_dir: Path) -> None:
    """Write ``metrics.json``, ``REPORT.md`` and ``site.json`` into ``results_dir``."""
    results_dir.mkdir(parents=True, exist_ok=True)
    (results_dir / "metrics.json").write_text(json.dumps(m, indent=2) + "\n", encoding="utf-8")
    (results_dir / "REPORT.md").write_text(render_report(m), encoding="utf-8")
    site = site_summary(m)
    (results_dir / "site.json").write_text(json.dumps(site, indent=2) + "\n", encoding="utf-8")
