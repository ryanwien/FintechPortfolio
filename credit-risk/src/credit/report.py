"""Render the validation report (``REPORT.md``) from the metrics dictionary.

Every number in the report is read from ``metrics``; nothing is typed by hand. Tables shared
with the model card come from ``credit.markdown``.
"""

from __future__ import annotations

from credit.config import FOUR_FIFTHS
from credit.markdown import fair_table, pct, perf_table, table
from credit.serialize import Metrics
from credit.strategy import fmt_usd


def _calib_table(m: Metrics) -> str:
    rows = [
        [
            r["decile"],
            r["count"],
            pct(r["predicted_pd"], 2),
            pct(r["observed"], 2),
            f"{r['ratio_obs_to_pred']:.2f}",
        ]
        for r in m["champion"]["calibration_by_decile"]
    ]
    return table(["Decile (1 = riskiest)", "N", "Predicted PD", "Observed", "Obs/Pred"], rows)


def _iv_table(m: Metrics) -> str:
    rows = [
        [
            r["feature"],
            f"{r['iv']:.4f}",
            r["strength"],
            r["bins"],
            "yes" if r["in_model"] else "no",
            "" if r["coefficient"] is None else f"{r['coefficient']:.3f}",
            f"{r['csi_dev_vs_oot']:.4f}",
        ]
        for r in m["champion"]["feature_iv"]
    ]
    return table(["Feature", "IV", "Strength", "Bins", "In model", "Coef", "CSI dev->OOT"], rows)


def _cutoff_table(m: Metrics) -> str:
    rows = [
        [
            r["cutoff"],
            pct(r["approval_rate"]),
            pct(r["bad_rate_approved"], 2),
            pct(r["expected_loss_rate"], 2),
            pct(r["realized_loss_rate"], 2),
            fmt_usd(r["expected_profit_cents"]),
            fmt_usd(r["realized_profit_cents"]),
        ]
        for r in m["strategy"]["oot_cutoff_table"]
    ]
    return table(
        [
            "Cutoff",
            "Approval",
            "Bad rate",
            "Exp. loss rate",
            "Realised loss rate",
            "Exp. profit",
            "Realised profit",
        ],
        rows,
    )


def _reason_table(m: Metrics) -> str:
    aa = m["adverse_action"]
    top4 = aa["top4_reason_counts"]
    rows = []
    for code, d in sorted(top4.items(), key=lambda kv: -kv[1]["count"]):
        prim = aa["primary_reason_counts"].get(code, {"count": 0})["count"]
        rows.append([code, d["statement"], prim, pct(prim / aa["declined_oot"]), d["count"]])
    return table(["Code", "Statement", "Primary", "Primary %", "In top 4"], rows)


def _samples(m: Metrics) -> str:
    lines = []
    for s in m["adverse_action"]["samples"]:
        lines.append(f"- Application {s['application_id']} (score {s['score']}):")
        for i, r in enumerate(s["reasons"], 1):
            lines.append(f"  {i}. {r['code']} {r['statement']} ({r['points_lost']} points)")
    return "\n".join(lines)


def render_report(m: Metrics) -> str:
    """Full validation report as Markdown."""
    d, c, ch, f, st, dec = (
        m["data"],
        m["champion"],
        m["challenger"],
        m["fairness"],
        m["strategy"],
        m["decision"],
    )
    at, allr = st["oot_at_cutoff"], st["oot_approve_all"]
    return f"""# Credit underwriting model - validation report

Generated by `python -m credit.run` (seed {d["seed"]}). All figures are from that run.

## Data

- {d["applicants"]:,} synthetic applications; development months {d["dev_months"]}
  ({d["development"]:,}, split {d["development_train"]:,} train / {d["development_holdout"]:,}
  in-time holdout), out-of-time months {d["oot_months"]} ({d["out_of_time"]:,}).
- Bad rate: development {pct(d["bad_rate_dev"], 2)}, out-of-time {pct(d["bad_rate_oot"], 2)}.
- Protected group B share: {pct(d["protected_group_share_B"])}. Used only for fairness testing.

## Discrimination

{perf_table(m)}

Challenger OOT AUC uplift vs champion: {ch["oot_auc_uplift_vs_champion"]:+.4f}
(threshold to adopt: +{dec["challenger_min_auc_uplift"]:.3f}). Decision: **{dec["champion"]}**.

## Calibration (champion, out-of-time)

Mean predicted PD {pct(c["oot_mean_predicted_pd"], 2)} vs observed
{pct(c["oot_observed_bad_rate"], 2)} (observed/predicted
{c["oot_calibration_ratio_obs_to_pred"]:.3f}).

{_calib_table(m)}

## Stability

Score PSI development vs out-of-time: {c["score_psi_dev_vs_oot"]:.4f} ({c["score_psi_label"]}).

## Information Value and characteristic stability

{_iv_table(m)}

Features removed for a wrong-signed coefficient: {", ".join(c["dropped_for_sign"]) or "none"}.

## Fair lending (out-of-time, at each model's profit cutoff)

{fair_table(m)}

AIR = approval rate of group B / approval rate of group A; the four-fifths rule flags
AIR < {FOUR_FIFTHS:.2f}. EO gap = approval rate among good (non-defaulting) applicants, A minus B.
Removing the region proxy costs {f["mitigation_auc_cost"]:.4f} OOT AUC
(tolerance {f["proxy_auc_tolerance"]}); mitigation adopted: {f["mitigation_adopted"]}.

## Cutoff strategy (champion, out-of-time)

Unit economics: lifetime margin {st["unit_economics"]["lifetime_margin"]}, LGD
{st["unit_economics"]["lgd"]}, EAD fraction {st["unit_economics"]["ead_fraction"]};
break-even PD {st["unit_economics"]["breakeven_pd"]} (score {st["breakeven_score"]}).

{_cutoff_table(m)}

Profit cutoff (chosen on the in-time holdout): **{st["profit_cutoff"]}**. On the OOT sample it
approves {pct(at["approval_rate"])} with a {pct(at["bad_rate_approved"], 2)} bad rate and a
realised profit of {fmt_usd(at["realized_profit_cents"])}, vs
{fmt_usd(allr["realized_profit_cents"])} if every applicant were approved
(bad rate {pct(allr["bad_rate_approved"], 2)}).

## Adverse action reasons (OOT declines at the profit cutoff)

{m["adverse_action"]["declined_oot"]:,} declined applicants;
{m["adverse_action"]["declined_with_4_reasons"]:,} received four reasons.

{_reason_table(m)}

Sample notices:

{_samples(m)}
"""
