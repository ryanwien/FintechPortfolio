"""Render the SR 11-7 style model card (``MODEL_CARD.md``) from the metrics dictionary.

Every figure is read from ``metrics`` or from the configuration constants the run used, so
the card cannot drift from the code. Tables shared with the report come from
``credit.markdown``.
"""

from __future__ import annotations

from credit.config import FOUR_FIFTHS, MIN_BIN_FRAC
from credit.data import LOAN_BOUNDS, LONG_TERM, SHORT_TERM
from credit.markdown import adopted_fairness, fair_table, pct, perf_table
from credit.metrics import PSI_AMBER, PSI_RED
from credit.serialize import Metrics
from credit.strategy import fmt_usd


def _monitoring_table() -> str:
    return f"""| Metric | Frequency | Amber | Red / action |
|---|---|---|---|
| Score PSI vs development | monthly | >= {PSI_AMBER:.2f} | >= {PSI_RED:.2f}: revalidate |
| Characteristic CSI | monthly | >= {PSI_AMBER:.2f} | >= {PSI_RED:.2f}: review binning |
| AUC / KS on matured vintages | quarterly | drop > 0.02 | drop > 0.05: redevelop |
| Observed / predicted bad rate | quarterly | outside 0.90-1.10 | outside 0.80-1.20: recalibrate |
| Adverse impact ratio at cutoff | quarterly | < 0.85 | < {FOUR_FIFTHS:.2f}: fair-lending review |
| Override rate and reason-code mix | monthly | +5 pts vs baseline | policy review |"""


def render_model_card(m: Metrics) -> str:
    """Model card as Markdown, structured after SR 11-7 / OCC 2011-12 documentation."""
    d, c, ch, f, st, dec, sc = (
        m["data"],
        m["champion"],
        m["challenger"],
        m["fairness"],
        m["strategy"],
        m["decision"],
        m["scaling"],
    )
    at = st["oot_at_cutoff"]
    econ = st["unit_economics"]
    adopted = "adopted" if f["mitigation_adopted"] else "not adopted"
    mono = ", ".join(f"{k} {v:+d}" for k, v in ch["monotonic_constraints"].items() if v)
    dropped = ", ".join(c["dropped_for_sign"]) or "none"
    loan_lo, loan_hi = LOAN_BOUNDS
    air = adopted_fairness(m)["adverse_impact_ratio"]
    return f"""# Model card: consumer instalment loan PD scorecard

*Generated by `python -m credit.run`. Structured after SR 11-7 / OCC 2011-12 model
documentation expectations. Synthetic data; not for production use.*

## 1. Purpose and intended use

- **Decision supported:** approve / decline for unsecured consumer instalment loans
  (${loan_lo:,}-${loan_hi:,}, {SHORT_TERM} or {LONG_TERM} months).
- **Output:** a points score (higher = safer) and a probability of default (PD) over
  the performance window.
  {sc["base_score"]:.0f} points = {sc["base_odds"]:.0f}:1 good:bad odds; every
  {sc["pdo"]:.0f} points doubles the odds (factor {sc["factor"]}, offset {sc["offset"]}).
- **Users:** credit policy (cutoff setting), underwriting operations (adverse action
  notices), finance (loss forecasting via PD).
- **Out of scope:** pricing, line management, secured lending, thin-file / no-file applicants,
  any population whose distribution differs materially from the development sample.

## 2. Data

- {d["applicants"]:,} synthetic applications generated in code (seed {d["seed"]}), months
  {d["dev_months"]} for development and {d["oot_months"]} held out as an out-of-time
  sample ({d["out_of_time"]:,}).
- Development bad rate {pct(d["bad_rate_dev"], 2)}; OOT bad rate {pct(d["bad_rate_oot"], 2)}.
  The OOT window includes deliberate drift (higher utilisation and inquiries, macro shift).
- **Protected attribute** (`protected_group`, {pct(d["protected_group_share_B"])} group B) is
  stored for fair-lending testing only and is rejected by the model constructors if offered as
  an input. It has no direct effect on default; it shifts income and region of residence.

## 3. Methodology

- **Champion:** WoE binning (quantile fine-classing, merged to >={MIN_BIN_FRAC:.0%} per bin and \
monotonic WoE),
  then logistic regression on WoE values, then linear scaling to points.
- **Variable selection:** candidates with IV below {c["min_iv"]} are excluded (excluded:
  {", ".join(c["dropped_for_low_iv"]) or "none"}); features whose fitted coefficient has the
  wrong sign are dropped and the model refit (dropped: {dropped}). All final
  coefficients negative: {c["all_coefficients_negative"]}.
- **Final characteristics:** {", ".join(c["features"])}.
- **Challenger:** histogram gradient boosting with monotonic constraints ({mono}).
- **Adverse action:** for each decline, points lost vs the maximum attainable points on each
  characteristic; the four largest map to ECOA / Reg B reason statements.

## 4. Performance

{perf_table(m)}

- OOT calibration: mean predicted PD {pct(c["oot_mean_predicted_pd"], 2)} vs observed
  {pct(c["oot_observed_bad_rate"], 2)} (ratio {c["oot_calibration_ratio_obs_to_pred"]:.3f}).
  Rank ordering holds across deciles; the level is under-predicted in the stressed OOT window.
- Score PSI development vs OOT: {c["score_psi_dev_vs_oot"]:.4f} ({c["score_psi_label"]}).

## 5. Fair-lending assessment

{fair_table(m)}

Mitigation tested: removing `region`, a geographic proxy correlated with the protected group.
OOT AUC cost {f["mitigation_auc_cost"]:.4f} against a tolerance of {f["proxy_auc_tolerance"]}:
mitigation **{adopted}**. Residual disparity after mitigation flows through income and credit
attributes that are legitimately predictive; it should be reviewed by fair-lending counsel for
business justification and less discriminatory alternatives.

## 6. Champion / challenger decision

Challenger OOT AUC {ch["oot"]["auc"]:.4f} vs champion {c["oot"]["auc"]:.4f} (uplift
{ch["oot_auc_uplift_vs_champion"]:+.4f}; adoption requires +{dec["challenger_min_auc_uplift"]:.3f}
and a passing AIR). **Champion: {dec["champion"]}.** The scorecard's additive points give
exact, auditable adverse action reasons; the challenger would need post-hoc attribution to
meet the same standard and does not earn that cost with this lift.

## 7. Cutoff and expected business outcome

Cutoff {st["profit_cutoff"]} maximises expected profit on the in-time holdout under the stated
unit economics (margin {econ["lifetime_margin"]}, LGD
{econ["lgd"]}, EAD {econ["ead_fraction"]}). On OOT applicants:
approval {pct(at["approval_rate"])}, bad rate {pct(at["bad_rate_approved"], 2)}, realised loss
rate {pct(at["realized_loss_rate"], 2)} of booked principal, realised profit
{fmt_usd(at["realized_profit_cents"])}.

## 8. Limitations

- Synthetic data with a known logit-additive generating process favours the scorecard; real
  bureau data has interactions and missingness that a GBM may exploit better.
- PD is calibrated to the development window; the OOT window shows under-prediction, so PD
  should not be used for loss forecasting without recalibration.
- Reject inference is not performed: the development sample is treated as through-the-door.
- Unit economics are flat assumptions (no term structure, prepayment or funding curve).
- Fairness testing uses a single binary protected attribute; real testing would cover each
  ECOA prohibited basis, with BISG proxies where the attribute is not collected.

## 9. Monitoring plan

{_monitoring_table()}

Current OOT readings: PSI {c["score_psi_dev_vs_oot"]:.4f}; observed/predicted
{c["oot_calibration_ratio_obs_to_pred"]:.3f}; AIR {air:.3f}.

## 10. Ownership and approvals

Model owner: credit risk analytics. Independent validation: model risk management (effective
challenge per SR 11-7 section V). Annual review, or sooner on any red trigger above.
"""
